const fn generate_all_voxels() -> [Voxel; 679] {
    let mut arr = [Voxel::Air; 679];
    let mut i = 0;
    while i < 679 {
        // Active gameplay blocks start at discriminant 3 (indices 3..=681)
        let id = (i + 3) as u16;
        arr[i] = unsafe { std::mem::transmute::<u16, Voxel>(id) };
        i += 1;
    }
    arr
}
