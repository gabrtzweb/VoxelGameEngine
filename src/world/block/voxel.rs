impl Voxel {
    /// Array containing all 612 active, non-placeholder gameplay voxels (indices 3..=614).
    pub const ALL: [Voxel; 612] = generate_all_voxels();

    /// Safely convert a `u16` id to a `Voxel` variant.
    #[inline(always)]
    pub const fn from_u16(val: u16) -> Option<Self> {
        if val <= 614 {
            // SAFETY: Voxel is #[repr(u16)] with contiguous discriminants from 0 to 614.
            Some(unsafe { std::mem::transmute::<u16, Self>(val) })
        } else {
            None
        }
    }
}

const fn generate_all_voxels() -> [Voxel; 612] {
    let mut arr = [Voxel::Air; 612];
    let mut i = 0;
    while i < 612 {
        // Active gameplay blocks start at discriminant 3 (indices 3..=614)
        let id = (i + 3) as u16;
        arr[i] = unsafe { std::mem::transmute::<u16, Voxel>(id) };
        i += 1;
    }
    arr
}
